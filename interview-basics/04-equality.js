// ┌───────────────────────────── 📖 ТЕОРІЯ ─────────────────────────────
// │ === (СТРОГА): різні типи → одразу false. Без жодних перетворень.
// │ ==  (НЕСТРОГА): різні типи → спершу ПРИВОДИТЬ до спільного типу, потім порівнює.
// │
// │ Спрощені правила ==:
// │   1. null == undefined → true, і більше вони ні з чим не рівні
// │   2. число і рядок   → рядок стає числом
// │   3. boolean         → спершу стає числом (true → 1, false → 0)
// │   4. об'єкт і примітив → об'єкт стає примітивом ([1,2] → '1,2', [] → '')
// │
// │   0 == ''       → true   ('' → 0)
// │   0 == '0'      → true   ('0' → 0)
// │   '' == '0'     → false  (обидва рядки → порівнюються як рядки!)
// │   [] == false   → true   ([] → '' → 0;  false → 0)
// │ Тобто 0 == '' і 0 == '0', але '' != '0'. == непередбачуване, тому пиши ===.
// │
// │ ── Неявне приведення в арифметиці ──
// │   +  з рядком   → СКЛЕЮВАННЯ:   '5' + 1 → '51'
// │   - * / %       → ЧИСЛО:        '5' - 1 → 4,   '5' * '2' → 10
// │   унарний +     → Number():     +'' → 0,  +'  42  ' → 42 (пробіли по краях ігноруються)
// │   true + 1 → 2  (true → 1)
// │   Об'єкти спершу стають рядком: [] + [] → '',  [] + {} → '[object Object]'
// │
// │ ── Порівняння > < ──
// │   рядок з рядком → ПОСИМВОЛЬНО, як у словнику: '10' > '9' → false ('1' < '9')
// │   рядок з числом → як ЧИСЛА:                 '10' > 9   → true
// │
// │ ── Object.is ──
// │ Це === з двома виправленнями:
// │                  ===     Object.is
// │   NaN, NaN      false    true
// │   0, -0         true     false
// │ В усьому іншому вони однакові. Як відрізнити -0: 1 / -0 → -Infinity.
// │
// │ 🗣 На співбесіді: «=== порівнює без перетворення типів, == спершу приводить
// │    операнди до спільного типу, звідси сюрпризи на кшталт [] == false.
// │    Я пишу ===, хіба що x == null. Object.is — це === з виправленням NaN і ±0».
// └──────────────────────────────────────────────────────────────────────

